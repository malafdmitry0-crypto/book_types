// Package closures показывает обобщённые алгоритмы через функции от индексов.
// Конкретные данные остаются в замыканиях вызывающего кода.
package closures

// FindIndex возвращает индекс первого совпадения или -1, если совпадений нет.
// При ошибке возвращает -1 и ошибку, прекращая обход.
// n должен быть неотрицательным и соответствовать данным, доступным test.
// test должен принимать каждый индекс в [0, n); паники не перехватываются.
// При n == 0 test не вызывается.
func FindIndex(n int, test func(int) (bool, error)) (int, error) {
	for i := 0; i < n; i++ {
		matched, err := test(i)
		if err != nil {
			return -1, err
		}
		if matched {
			return i, nil
		}
	}
	return -1, nil
}
